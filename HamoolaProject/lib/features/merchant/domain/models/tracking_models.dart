/// Filter criteria for drivers on the map and search list (Image 1)
class DriverFilterCriteria {
  final String vehicleCategory; // 'all', 'شاحنات', 'قاطرات', 'دينات', 'تبريد', 'أخرى'
  final String availabilityStatus; // 'all', 'available', 'busy', 'offline'
  final String governorate; // 'all' (جميع المحافظات) or 'صنعاء', 'عدن', etc.
  final String cityOrDistrict; // 'all' (جميع المدن والمناطق) or specific district
  final String cargoType; // 'all' or 'مواد بناء', 'مواد غذائية', 'أثاث', 'مواد نفطية', 'أخرى'

  const DriverFilterCriteria({
    this.vehicleCategory = 'all',
    this.availabilityStatus = 'all',
    this.governorate = 'all',
    this.cityOrDistrict = 'all',
    this.cargoType = 'all',
  });

  bool get isDefault =>
      vehicleCategory == 'all' &&
      availabilityStatus == 'all' &&
      governorate == 'all' &&
      cityOrDistrict == 'all' &&
      cargoType == 'all';

  DriverFilterCriteria copyWith({
    String? vehicleCategory,
    String? availabilityStatus,
    String? governorate,
    String? cityOrDistrict,
    String? cargoType,
  }) {
    return DriverFilterCriteria(
      vehicleCategory: vehicleCategory ?? this.vehicleCategory,
      availabilityStatus: availabilityStatus ?? this.availabilityStatus,
      governorate: governorate ?? this.governorate,
      cityOrDistrict: cityOrDistrict ?? this.cityOrDistrict,
      cargoType: cargoType ?? this.cargoType,
    );
  }
}

