enum TripStage {
  toLoading,
  loaded,
  inTransit,
  arrived,
}

/// The 9 sequential execution stages of a trip in Hamula (Prompt 09 — Section 8)
enum TripExecutionStage {
  agreementConfirmedAndPaid(1, 'تم تأكيد الاتفاق والدفع', 'تم توثيق الاتفاق وخصم الأجرة وبدء الاستعداد'),
  preparingForLoading(2, 'الاستعداد للتحميل', 'السائق يجهز الشاحنة ومعدات التثبيت'),
  arrivedAtLoading(3, 'الوصول إلى موقع التحميل', 'وصول الشاحنة إلى مستودع التحميل'),
  loadingStarted(4, 'بدء التحميل', 'جاري شحن وتستيف البضائع في الشاحنة'),
  loadingCompletedAndTripStarted(5, 'اكتمال التحميل وبدء الرحلة', 'تم استلام البوليصة وانطلاق الشاحنة'),
  inTransit(6, 'متابعة الرحلة', 'الشاحنة تسير على الطريق السريع نحو الوجهة'),
  arrivedAtDelivery(7, 'الوصول إلى موقع التسليم', 'وصول الشاحنة إلى رصيف التفريغ والتسليم'),
  deliveryConfirmed(8, 'تأكيد التسليم', 'تم فحص الشحنة وتأكيد استلام العميل بنجاح'),
  tripClosed(9, 'إغلاق الرحلة والتقييم', 'تم إغلاق الرحلة رسمياً وتسوية المستحقات وتفعيل التقييم');

  final int stepNumber;
  final String title;
  final String description;
  const TripExecutionStage(this.stepNumber, this.title, this.description);

  static TripExecutionStage fromStepNumber(int step) {
    return TripExecutionStage.values.firstWhere(
      (s) => s.stepNumber == step,
      orElse: () => TripExecutionStage.agreementConfirmedAndPaid,
    );
  }

  /// Maps to visual vector map stage
  TripStage get toLegacyStage {
    if (stepNumber <= 4) return TripStage.toLoading;
    if (stepNumber == 5) return TripStage.loaded;
    if (stepNumber == 6) return TripStage.inTransit;
    return TripStage.arrived;
  }
}

